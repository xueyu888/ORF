export function applyDesignTokens(appearanceMode: AppearanceMode = "light", root: HTMLElement = document.documentElement) {
  const variables = appearanceMode === "dark"
    ? { ...designCssVariables, ...darkDesignCssVariables }
    : designCssVariables;
  for (const [name, value] of Object.entries(variables)) {
    root.style.setProperty(name, value);
  }
}
